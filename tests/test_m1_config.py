class TestLoaderStrictness(unittest.TestCase):
    def _write(self, tmpdir, name, content):
        import tempfile
        path = os.path.join(tempfile.mkdtemp(dir=tmpdir), name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return path

    def test_missing_file_raises(self):
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config("does_not_exist.yaml")

    def test_invalid_yaml_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "bad.yaml", "categories: [unclosed")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_non_mapping_root_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "list.yaml", "- just\n- a\n- list\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_missing_required_key_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "lexicon.yaml", "residual_label: Other/No-Frame\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_non_string_keyword_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "lexicon.yaml",
                        "residual_label: Other/No-Frame\n"
                        "category_priority:\n- C1\n"
                        "categories:\n  C1:\n  - ok\n  - 123\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_priority_order_mismatch_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "lexicon.yaml",
                        "residual_label: Other/No-Frame\n"
                        "category_priority:\n- B\n- A\n"
                        "categories:\n  A:\n  - k1\n  B:\n  - k2\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_empty_category_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "lexicon.yaml",
                        "residual_label: Other/No-Frame\n"
                        "category_priority:\n- C1\n"
                        "categories:\n  C1: []\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config(p)

    def test_rules_bad_passthrough_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "rules.yaml",
                        "stance_target: T\nvariants:\n  x_v2:\n    critical:\n    - a\n"
                        "    supportive:\n    - b\n    passthrough: {}\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_rules_config(p)

    def test_pipeline_bad_threshold_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "pipeline.yaml",
                        "language_detection:\n  langdetect_seed: 0\n  min_chars: -5\n"
                        "preprocessing:\n  lead_max_words: 250\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_pipeline_config(p)

    def test_models_bad_label_count_raises(self):
        import tempfile
        d = tempfile.mkdtemp()
        p = self._write(d, "models.yaml",
                        "sentiment:\n  model_name: m\n  label_order:\n  - Only\n  - Two\n")
        with self.assertRaises(cl.ConfigError):
            cl.load_models_config(p)

    def test_no_silent_fallback_on_load_failure(self):
        # the loader must never return a default configuration object
        with self.assertRaises(cl.ConfigError):
            cl.load_framing_config("missing.yaml")
        self.assertIsNone(getattr(cl, "_DEFAULTS", None))


class TestRunInferenceUsesConfig(unittest.TestCase):
    def test_label_order_and_model_name(self):
        import importlib.util
        spec = importlib.util.spec_from_file_location(
            "run_inference_module", os.path.join(ROOT, "src", "run_inference.py"))
        ri = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(ri)
        self.assertEqual(ri.MODEL_NAME, W_MODEL_NAME)
        self.assertEqual(ri.LABELS, W_LABEL_ORDER)
        # index order must cover all three classes (guards the M1 integration
        # fix of the string-keyed LABEL_MAP that could never be indexed by int)
        for idx in range(3):
            self.assertIsInstance(ri.LABELS[idx], str)


