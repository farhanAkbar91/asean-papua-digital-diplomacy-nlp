class TestConfigFilesLoad(unittest.TestCase):
    def test_all_yaml_files_exist_and_are_mappings(self):
        for name in ["lexicon.yaml", "rules.yaml", "pipeline.yaml", "models.yaml"]:
            path = os.path.join(CONFIGS, name)
            self.assertTrue(os.path.isfile(path), f"missing {path}")
            with open(path, encoding="utf-8") as f:
                data = yaml.safe_load(f)
            self.assertIsInstance(data, dict, name)

    def test_deterministic_loading(self):
        a = cl.load_framing_config()
        b = cl.load_framing_config()
        self.assertEqual(a, b)
        self.assertEqual(list(a["categories"].keys()), W_FRAMING_ORDER)  # order preserved


